'use client';

import { useState } from 'react';
import { useTranslations } from 'next-intl';
import type { ProfileContent } from '@resumaker/shared';
import { ContactCard } from '@/components/builder/sections/contact-card';
import { SummaryCard } from '@/components/builder/sections/summary-card';
import { ExperienceSection } from '@/components/builder/sections/experience-section';
import { EducationSection } from '@/components/builder/sections/education-section';
import { ProjectsSection } from '@/components/builder/sections/projects-section';
import { SkillsSection } from '@/components/builder/sections/skills-section';
import { CertificationsSection } from '@/components/builder/sections/certifications-section';
import { AwardsSection } from '@/components/builder/sections/awards-section';
import { LanguagesSection } from '@/components/builder/sections/languages-section';

/**
 * Composes every profile section into the always-visible /career-profile
 * page. Replaces the old per-resume AdvancedEditor — same section
 * components, repointed at the one canonical ProfileContent instead of
 * an individual resume's content, since there's no more per-resume hand
 * editing (resumes are generated by tailoring this shared profile to a
 * job description, not edited independently).
 *
 * Owns the single-edit rule (one `editingId` across all multi-entry
 * sections — switching while another card is mid-edit prompts to save
 * / discard). Contact has no editingId participation — it's always
 * open, not click-to-expand, per its own component's doc comment.
 */

export interface ProfileEditorProps {
  content: ProfileContent;
  onChange: (next: ProfileContent) => void;
}

export function ProfileEditor({ content, onChange }: ProfileEditorProps) {
  const t = useTranslations('builder.advancedEditor');
  const [editingId, setEditingId] = useState<string | null>(null);

  function trySetEditingId(next: string | null) {
    if (editingId && next && editingId !== next) {
      const ok = window.confirm(t('confirmDiscard'));
      if (!ok) return;
    }
    setEditingId(next);
  }

  function patch<K extends keyof ProfileContent>(key: K, value: ProfileContent[K]) {
    onChange({ ...content, [key]: value });
  }

  return (
    <div className="space-y-6">
      <ContactCard contact={content.contact} onChange={(c) => patch('contact', c)} />
      <SummaryCard
        summary={content.summary}
        onChange={(s) => patch('summary', s)}
        editingId={editingId}
        onSetEditingId={trySetEditingId}
        jobDescription=""
      />
      <ExperienceSection
        entries={content.experience}
        onChange={(e) => patch('experience', e)}
        editingId={editingId}
        onSetEditingId={trySetEditingId}
        jobDescription=""
      />
      <EducationSection
        entries={content.education}
        onChange={(e) => patch('education', e)}
        editingId={editingId}
        onSetEditingId={trySetEditingId}
      />
      <ProjectsSection
        entries={content.projects ?? []}
        onChange={(e) => patch('projects', e)}
        editingId={editingId}
        onSetEditingId={trySetEditingId}
      />
      <SkillsSection skills={content.skills} onChange={(s) => patch('skills', s)} />
      <CertificationsSection
        entries={content.certifications ?? []}
        onChange={(c) => patch('certifications', c)}
        editingId={editingId}
        onSetEditingId={trySetEditingId}
      />
      <AwardsSection
        entries={content.awards ?? []}
        onChange={(a) => patch('awards', a)}
        editingId={editingId}
        onSetEditingId={trySetEditingId}
      />
      <LanguagesSection
        languages={content.languages ?? []}
        onChange={(l) => patch('languages', l)}
      />
    </div>
  );
}
